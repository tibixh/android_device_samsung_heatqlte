#!/bin/bash
set -euo pipefail

DEVICE=heatqlte
VENDOR=samsung

OUTDIR="vendor/$VENDOR/$DEVICE"
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ANDROID_ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"

PROPRIETARY_FILES="$SCRIPT_DIR/proprietary-files.txt"
VENDOR_DIR="$ANDROID_ROOT/$OUTDIR"
MAKEFILE="$VENDOR_DIR/$DEVICE-vendor.mk"
ANDROIDMK="$VENDOR_DIR/Android.mk"
BOARDCONFIG="$VENDOR_DIR/BoardConfigVendor.mk"

if [[ ! -f "$PROPRIETARY_FILES" ]]; then
    echo "ERROR: Cannot find $PROPRIETARY_FILES" >&2
    exit 1
fi

mkdir -p "$VENDOR_DIR"

# Return the module name without its final extension.
module_name() {
    local BASE="${1##*/}"

    if [[ "$BASE" == *.* && "$BASE" != .* ]]; then
        BASE="${BASE%.*}"
    fi

    printf '%s' "$BASE"
}

# Return the module's final extension, including the dot.
module_extension() {
    local BASE="${1##*/}"

    if [[ "$BASE" == *.* && "$BASE" != .* ]]; then
        printf '.%s' "${BASE##*.}"
    fi
}

# Separate ordinary copied files from prebuilt modules.
declare -a SOURCES=()
declare -a DESTS=()
declare -a MODULE_SOURCES=()
declare -a MODULE_DESTS=()

while IFS= read -r LINE || [[ -n "$LINE" ]]; do
    # Remove comments and surrounding whitespace.
    LINE="${LINE%%#*}"
    LINE="${LINE#"${LINE%%[![:space:]]*}"}"
    LINE="${LINE%"${LINE##*[![:space:]]}"}"

    # Skip empty lines.
    [[ -z "$LINE" ]] && continue

    # A leading '-' declares a prebuilt module.
    IS_MODULE=0
    if [[ "$LINE" == -* ]]; then
        IS_MODULE=1
        LINE="${LINE#-}"
    fi

    # Ignore device-specific source suffix
    LINE="${LINE%%|*}"

    # Parse source[:destination].
    if [[ "$LINE" == *:* ]]; then
        SRC="${LINE%%:*}"
        DEST="${LINE#*:}"
    else
        SRC="$LINE"
        DEST="$LINE"
    fi

    # Trim whitespace around both paths (supports "source : destination").
    SRC="${SRC#"${SRC%%[![:space:]]*}"}"
    SRC="${SRC%"${SRC##*[![:space:]]}"}"
    DEST="${DEST#"${DEST%%[![:space:]]*}"}"
    DEST="${DEST%"${DEST##*[![:space:]]}"}"

    [[ -z "$SRC" ]] && continue
    [[ -z "$DEST" ]] && DEST="$SRC"

    if (( IS_MODULE )); then
        MODULE_SOURCES+=("$SRC")
        MODULE_DESTS+=("$DEST")
    else
        SOURCES+=("$SRC")
        DESTS+=("$DEST")
    fi
done < <(sort "$PROPRIETARY_FILES")

COPY_COUNT=${#SOURCES[@]}
MODULE_COUNT=${#MODULE_SOURCES[@]}

# Generate the vendor product makefile.
{
    cat <<EOF
# Copyright (C) 2011-2014 The CyanogenMod Project
#
# Licensed under the Apache License, Version 2.0 (the "License");
# you may not use this file except in compliance with the License.
# You may obtain a copy of the License at
#
#      http://www.apache.org/licenses/LICENSE-2.0
#
# Unless required by applicable law or agreed to in writing, software
# distributed under the License is distributed on an "AS IS" BASIS,
# WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
# See the License for the specific language governing permissions and
# limitations under the License.

# This file is generated by device/$VENDOR/$DEVICE/setup-makefiles.sh
EOF

    if (( COPY_COUNT > 0 )); then
        printf 'PRODUCT_COPY_FILES += \\\n'

        for ((i = 0; i < COPY_COUNT; i++)); do
            if (( i < COPY_COUNT - 1 )); then
                printf '    %s/proprietary/%s:system/%s \\\n' \
                    "$OUTDIR" "${DESTS[i]}" "${DESTS[i]}"
            else
                printf '    %s/proprietary/%s:system/%s\n' \
                    "$OUTDIR" "${DESTS[i]}" "${DESTS[i]}"
            fi
        done
    fi

    if (( MODULE_COUNT > 0 )); then
        printf '\nPRODUCT_PACKAGES += \\\n'

        for ((i = 0; i < MODULE_COUNT; i++)); do
            MODULE_NAME="$(module_name "${MODULE_DESTS[i]}")"

            if (( i < MODULE_COUNT - 1 )); then
                printf '    %s \\\n' "$MODULE_NAME"
            else
                printf '    %s\n' "$MODULE_NAME"
            fi
        done
    fi
} > "$MAKEFILE"

# Generate Android.mk containing the prebuilt module declarations.
{
    cat <<EOF
# Copyright (C) 2011-2014 The CyanogenMod Project
#
# Licensed under the Apache License, Version 2.0 (the "License");
# you may not use this file except in compliance with the License.
# You may obtain a copy of the License at
#
#      http://www.apache.org/licenses/LICENSE-2.0
#
# Unless required by applicable law or agreed to in writing, software
# distributed under the License is distributed on an "AS IS" BASIS,
# WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
# See the License for the specific language governing permissions and
# limitations under the License.

# This file is generated by device/$VENDOR/$DEVICE/setup-makefiles.sh

LOCAL_PATH := \$(call my-dir)

ifeq (\$(TARGET_DEVICE),$DEVICE)
EOF

    for ((i = 0; i < MODULE_COUNT; i++)); do
        DEST="${MODULE_DESTS[i]}"

        MODULE_NAME="$(module_name "$DEST")"
        EXTENSION="$(module_extension "$DEST")"
        DEST_DIR="${DEST%/*}"

        if [[ "$DEST_DIR" == "$DEST" ]]; then
            DEST_DIR=""
        fi

        # Infer module type from its destination path.
        case "$DEST" in
            lib/*.so|vendor/lib/*.so|lib64/*.so|vendor/lib64/*.so)
                MODULE_CLASS="SHARED_LIBRARIES"
                ;;
            app/*.apk|vendor/app/*.apk|priv-app/*.apk|vendor/priv-app/*.apk)
                MODULE_CLASS="APPS"
                ;;
            framework/*.jar|vendor/framework/*.jar)
                MODULE_CLASS="JAVA_LIBRARIES"
                ;;
            bin/*|vendor/bin/*|sbin/*|vendor/sbin/*)
                MODULE_CLASS="EXECUTABLES"
                ;;
            *)
                MODULE_CLASS="ETC"
                ;;
        esac

        printf '\ninclude $(CLEAR_VARS)\n'
        printf 'LOCAL_MODULE := %s\n' "$MODULE_NAME"
        printf 'LOCAL_SRC_FILES := proprietary/%s\n' "$DEST"
        printf 'LOCAL_MODULE_CLASS := %s\n' "$MODULE_CLASS"
        printf 'LOCAL_MODULE_TAGS := optional\n'

        if [[ -n "$EXTENSION" ]]; then
            printf 'LOCAL_MODULE_SUFFIX := %s\n' "$EXTENSION"
        fi

        # Preserve the destination directory in the system image.
        if [[ -n "$DEST_DIR" ]]; then
            printf 'LOCAL_MODULE_PATH := $(TARGET_OUT)/%s\n' "$DEST_DIR"
        else
            printf 'LOCAL_MODULE_PATH := $(TARGET_OUT)\n'
        fi

        # APKs already have their own signatures.
        if [[ "$MODULE_CLASS" == "APPS" ]]; then
            printf 'LOCAL_CERTIFICATE := PRESIGNED\n'

            case "$DEST" in
                priv-app/*|vendor/priv-app/*)
                    printf 'LOCAL_PRIVILEGED_MODULE := true\n'
                    ;;
            esac
        fi

        # Specify the architecture for shared libraries.
        if [[ "$MODULE_CLASS" == "SHARED_LIBRARIES" ]]; then
            case "$DEST" in
                lib64/*|vendor/lib64/*)
                    printf 'LOCAL_MULTILIB := 64\n'
                    ;;
                lib/*|vendor/lib/*)
                    printf 'LOCAL_MULTILIB := 32\n'
                    ;;
            esac
        fi

        printf 'include $(BUILD_PREBUILT)\n'
    done

    printf '\nendif\n'
} > "$ANDROIDMK"

